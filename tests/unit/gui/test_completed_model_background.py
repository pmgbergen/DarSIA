"""After training, the model list and post-training views are read in the background."""
import json
import threading
from types import SimpleNamespace as NS

import pytest
from PySide6.QtWidgets import QCheckBox, QLabel, QSpinBox, QWidget

from darsia.fluidflower.ui import model_training as ui

Page = ui.SharedPhaseModelTrainingPage


def test_a_completed_model_is_recorded_without_scanning_the_library(tmp_path):
    calls = []
    page = NS(_completed_model_roots={}, _sync_completed_model_roots=lambda: None,
              _model_filter_settings=NS(setValue=lambda *_a: None, sync=lambda: None),
              _request_async_model_refresh=lambda: calls.append("background"),
              _refresh_model_history=lambda: pytest.fail("The library was scanned on the GUI thread"))
    root = tmp_path / "phase-model-new"
    Page._record_completed_model(page, "phase-model-new", root)
    assert calls == ["background"] and page._completed_model_root == str(root.resolve())


def test_the_new_model_is_selected_once_listed_and_its_views_follow(tmp_path):
    root = str((tmp_path / "phase-model-new").resolve())
    request = dict(post_training_view_scope="reviewed")
    selected, prepared, listed = [], [], {"value": False}
    page = NS(_completed_model_root=root, _post_training_requests={root.casefold(): request},
              select_validation_model=lambda value, series_context=False:
                  selected.append((value, series_context)) or listed["value"],
              _prepare_post_training_views=lambda value, path: prepared.append((value, str(path))))
    Page._select_completed_model(page)  # Not listed yet: wait for the next catalogue answer.
    assert page._completed_model_root == root and not prepared
    listed["value"] = True
    Page._select_completed_model(page)
    assert selected[-1] == (root, True) and page._completed_model_root is None
    assert prepared == [(request, root)] and not page._post_training_requests
    page._completed_model_root = root
    Page._note_model_catalog_selection(page)  # A choice made meanwhile wins.
    assert page._completed_model_root is None


def test_post_training_views_are_read_off_the_gui_thread(qtbot, tmp_path):
    host = QWidget()
    qtbot.addWidget(host)
    host.status, host.series_batch_workers, host.series_batch_gpu = QLabel(), QSpinBox(), QCheckBox()
    host.series_batch_workers.setRange(1, 64)
    host.review_sessions = []
    host._selected_validation_model = lambda: dict(model_id="M", root=str(tmp_path), series_scope="ffac")
    threads = []

    def runs(root):
        threads.append(threading.current_thread() is threading.main_thread())
        return ["ac17", "ac18"]

    def binding(entry, *, review_sessions=None):
        threads.append(threading.current_thread() is threading.main_thread())
        return dict(selected_candidates={"ac17": "saved"})

    host._reviewed_training_runs, host._validation_binding = runs, binding
    host._post_training_views_read = lambda value, error: Page._post_training_views_read(host, value, error)
    request = dict(post_training_view_scope="reviewed", post_training_cpu_workers=6, post_training_gpu_worker=True)
    Page._prepare_post_training_views(host, request, tmp_path)
    assert host.status.text().startswith("Model fitted. Checking which reviewed experiments")
    qtbot.waitUntil(lambda: (tmp_path / "post_training_view_plan.json").is_file(), timeout=10000)
    assert threads == [False, False]
    plan = json.loads((tmp_path / "post_training_view_plan.json").read_text(encoding="utf-8"))
    assert plan["requested_runs"] == ["ac17", "ac18"] and plan["already_prepared"] == ["ac17"]
    assert host.series_batch_workers.value() == 6 and host.series_batch_gpu.isChecked()
    assert host.status.text() == "Model fitted. Missing phase maps are not generated by the saved-review workspace."
