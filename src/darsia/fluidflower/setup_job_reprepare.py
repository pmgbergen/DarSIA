def _original_plan(root, job, stores):
    from .store_map import require_input_containment
    from .pipeline.capacity import read_bound
    from .pipeline.series_setup_protocol import validate_setup_plan
    reference = job["setup_plan"]
    path = require_input_containment(reference, stores, job["series_id"])
    bound = dict(path=str(path), sha256=reference["sha256"], size_bytes=reference["bytes"])
    plan = validate_setup_plan(read_bound(bound)[0])
