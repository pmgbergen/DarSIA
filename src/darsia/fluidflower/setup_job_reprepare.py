def _rename(source, destination):
    """Retry one unchanged transaction move while Windows readers close."""
    source, destination = Path(source), Path(destination)
    directory = source.is_dir()
    def identity(path):
        value = _identity(path, directory=directory)
        if directory:
            return value
        pin = descriptor(path)
        return value, pin["sha256"], pin["size_bytes"]
    original = identity(source)
    attempted = False
    def move():
        nonlocal attempted
        try:
            current = identity(source)
        except FileNotFoundError:
            if attempted and destination.exists() and identity(destination) == original:
                return  # A transient NAS response hid this exact completed move.
            raise
        if current != original:
            raise ValueError("Setup transaction source changed before its move: " + str(source))
        if destination.exists():
            raise FileExistsError(str(destination))
        attempted = True
        try:
            source.rename(destination)
        except OSError:
            if not source.exists() and destination.exists() and identity(destination) == original:
                return
            raise
    retry_transient(move)


def _preserved_entries(root, job, plan, stores):
    """Keep declared input/RAW namespaces, not a whitelist of runtime folders."""
    preserved = set(_PRESERVED)
    roots = stores.roots(job["series_id"])
    from .storage_paths import _alias_rows, _resolve_with
    aliases = _alias_rows()
    if (Path(roots["results"]) / job["job_id"]).resolve() == root.resolve():
        preserved.update(job["expected_runs"])

    def keep(path):
        path = _resolve_with(path, aliases)
        if path.is_absolute() and path.is_relative_to(root) and path != root:
            preserved.add(path.relative_to(root).parts[0])

    def sources(value):
        if isinstance(value, dict):
            if isinstance(value.get("path"), str) and "sha256" in value:
                keep(value["path"])
            elif (isinstance(value.get("root_alias"), str) and value["root_alias"] in roots
                    and isinstance(value.get("relative_path"), str)
                    and "sha256" in value):
                keep(Path(roots[value["root_alias"]]) / value["relative_path"])
            for child in value.values():
                sources(child)
        elif isinstance(value, list):
            for child in value:
                sources(child)
    sources(plan)
    if job.get("image_preparation"):
        from .pipeline.series_setup_jobs import _control
        config, pin = _control(job["image_preparation"]["configuration"]["path"])
        if pin != job["image_preparation"]["configuration"]:
            raise ValueError("Image preparation output authority changed")
        keep(config["output_root"])
    for build in plan["build_plans"]:
        keep(build["request_template"]["output"]["destination"])
    return preserved


def _claim_observations(root, reviewed_attempts):
    """Check known observations without treating them as ownership evidence."""
    directory = root / "claim_observations"
    if not directory.exists():
        return
    from pathlib import PurePosixPath
    for path in directory.glob("*.json"):
        value = read_json(path)
        if value.get("state") != "ownerless_claim_first_observed":
            continue  # Opaque runtime metadata is retained, never promoted.
        run, token = value.get("run"), value.get("attempt_id")
        relative = PurePosixPath(value.get("claimed_relative_path", ""))
        if (not isinstance(token, str) or path.name != str(run) + "." + token + ".json"
                or relative.is_absolute() or ".." in relative.parts or len(relative.parts) != 3
                or relative.parts[0] != "claimed" or relative.parts[-1] != str(run) + ".json"
                or (run, token) not in reviewed_attempts):
            raise ValueError("Runtime claim observation differs from the reviewed original claim")
        task = read_json(root.joinpath(*relative.parts))
        if task.get("run") != run or task.get("attempt_id") != token:
            raise ValueError("Runtime claim observation no longer binds its original task")


